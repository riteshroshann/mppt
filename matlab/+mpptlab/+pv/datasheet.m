function ds = datasheet(name)

    arguments
        name (1,1) string = "KC200GT"
    end

    catalogue = struct();

    catalogue.KC200GT = struct( ...
        "Name",       "Kyocera KC200GT", ...
        "Technology", "multi-crystalline Si", ...
        "Ns",         54, ...
        "Voc",        32.9, ...
        "Isc",        8.21, ...
        "Vmp",        26.3, ...
        "Imp",        7.61, ...
        "Pmax",       200.143, ...
        "betaVocPct", -0.3739, ...
        "alphaIscPct", 0.0387, ...
        "NOCT",       47.0);

    catalogue.SPR305 = struct( ...
        "Name",       "SunPower SPR-305E-WHT-D", ...
        "Technology", "mono-crystalline Si", ...
        "Ns",         96, ...
        "Voc",        64.2, ...
        "Isc",        5.96, ...
        "Vmp",        54.7, ...
        "Imp",        5.58, ...
        "Pmax",       305.226, ...
        "betaVocPct", -0.27269, ...
        "alphaIscPct", 0.061745, ...
        "NOCT",       45.0);

    key = matlab.lang.makeValidName(name);
    if ~isfield(catalogue, key)
        error("mpptlab:pv:unknownModule", ...
            "Unknown module '%s'. Available: %s.", ...
            name, strjoin(string(fieldnames(catalogue)), ", "));
    end

    ds = catalogue.(key);
    ds.Key      = string(key);
    ds.betaVoc  = ds.betaVocPct  / 100 * ds.Voc;
    ds.alphaIsc = ds.alphaIscPct / 100 * ds.Isc;
    ds.PmaxCheck = ds.Vmp * ds.Imp;
    ds.FF        = ds.Pmax / (ds.Voc * ds.Isc);
end
